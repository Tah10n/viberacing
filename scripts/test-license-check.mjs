import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import process from "node:process";

const checker = resolve(import.meta.dirname, "check-licenses.mjs");
const fixtureRoot = mkdtempSync(join(tmpdir(), "viberacing-license-check-"));
const fixtureToolIntegrity = `sha512-${Buffer.from("fixture-tool").toString("base64")}`;
const fixtureRuntimeIntegrity = `sha512-${Buffer.from("fixture-runtime").toString("base64")}`;
const platformOnlyIntegrity = `sha512-${Buffer.from("platform-only").toString("base64")}`;

function makeFixture(name, { workspace = false } = {}) {
  const directory = join(fixtureRoot, name);
  mkdirSync(join(directory, "config"), { recursive: true });
  mkdirSync(join(directory, "docs", "reference"), { recursive: true });
  mkdirSync(
    join(directory, "node_modules", ".pnpm", "fixture-tool@1.0.0", "node_modules", "fixture-tool"),
    {
      recursive: true,
    },
  );
  mkdirSync(join(directory, ".github", "workflows"), { recursive: true });
  if (workspace) {
    mkdirSync(join(directory, "apps", "web"), { recursive: true });
    mkdirSync(
      join(
        directory,
        "node_modules",
        ".pnpm",
        "fixture-runtime@2.0.0",
        "node_modules",
        "fixture-runtime",
      ),
      { recursive: true },
    );
  }
  writeFileSync(
    join(directory, "package.json"),
    `${JSON.stringify(
      {
        name: "fixture",
        private: true,
        devDependencies: { "fixture-tool": "1.0.0" },
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  writeFileSync(
    join(
      directory,
      "node_modules",
      ".pnpm",
      "fixture-tool@1.0.0",
      "node_modules",
      "fixture-tool",
      "package.json",
    ),
    `${JSON.stringify({ name: "fixture-tool", version: "1.0.0", license: "MIT" }, null, 2)}\n`,
    "utf8",
  );
  if (workspace) {
    writeFileSync(
      join(directory, "apps", "web", "package.json"),
      `${JSON.stringify(
        {
          name: "@fixture/web",
          private: true,
          dependencies: { "fixture-runtime": "2.0.0" },
        },
        null,
        2,
      )}\n`,
      "utf8",
    );
    writeFileSync(
      join(
        directory,
        "node_modules",
        ".pnpm",
        "fixture-runtime@2.0.0",
        "node_modules",
        "fixture-runtime",
        "package.json",
      ),
      `${JSON.stringify({ name: "fixture-runtime", version: "2.0.0", license: "MIT" }, null, 2)}\n`,
      "utf8",
    );
  }
  writeFileSync(
    join(directory, "pnpm-lock.yaml"),
    `lockfileVersion: '9.0'
importers:
  .:
    devDependencies:
      fixture-tool:
        specifier: 1.0.0
        version: 1.0.0
${
  workspace
    ? `  apps/web:
    dependencies:
      fixture-runtime:
        specifier: 2.0.0
        version: 2.0.0
`
    : ""
}packages:
  fixture-tool@1.0.0:
    resolution: {integrity: ${fixtureToolIntegrity}}
  platform-only@1.0.0:
    resolution: {integrity: ${platformOnlyIntegrity}}
${
  workspace
    ? `  fixture-runtime@2.0.0:
    resolution: {integrity: ${fixtureRuntimeIntegrity}}
`
    : ""
}`,
    "utf8",
  );
  writeFileSync(
    join(directory, "Cargo.toml"),
    '[workspace]\nmembers = []\nresolver = "3"\n',
    "utf8",
  );
  writeFileSync(
    join(directory, "Cargo.lock"),
    "# This file is automatically @generated by Cargo.\nversion = 4\n",
    "utf8",
  );
  writeFileSync(join(directory, "compose.yaml"), "services: {}\n", "utf8");
  writeFileSync(join(directory, ".github", "workflows", "ci.yml"), "jobs: {}\n", "utf8");
  writeFileSync(
    join(directory, "config", "license-policy.json"),
    `${JSON.stringify(
      {
        schemaVersion: 1,
        approvedNpmLicenseExpressions: ["MIT"],
        approvedCargoLicenseExpressions: [],
        externalArtifacts: [],
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  const metadataPackages = [
    ...(workspace
      ? [
          {
            name: "fixture-runtime",
            version: "2.0.0",
            license: "MIT",
            integrity: fixtureRuntimeIntegrity,
          },
        ]
      : []),
    {
      name: "fixture-tool",
      version: "1.0.0",
      license: "MIT",
      integrity: fixtureToolIntegrity,
    },
    {
      name: "platform-only",
      version: "1.0.0",
      license: "MIT",
      integrity: platformOnlyIntegrity,
    },
  ];
  writeFileSync(
    join(directory, "config", "npm-package-metadata.json"),
    `${JSON.stringify(
      {
        schemaVersion: 1,
        registry: "https://registry.npmjs.org",
        packages: metadataPackages,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  writeFileSync(
    join(directory, "THIRD_PARTY_NOTICES.md"),
    `| [fixture-tool](https://example.com/) | Test | MIT |
${workspace ? "| [fixture-runtime](https://example.com/runtime) | Runtime test | MIT |\n" : ""}`,
    "utf8",
  );
  return directory;
}

function run(directory, ...args) {
  return spawnSync(process.execPath, [checker, "--root", directory, ...args], {
    cwd: directory,
    encoding: "utf8",
  });
}

function expectPass(label, result) {
  if (result.status !== 0) {
    throw new Error(`${label} unexpectedly failed:\n${result.stdout}${result.stderr}`);
  }
}

function expectFailure(label, result, expectedText) {
  const output = `${result.stdout}${result.stderr}`;
  if (result.status === 0 || !output.includes(expectedText)) {
    throw new Error(`${label} did not fail with ${expectedText}:\n${output}`);
  }
}

try {
  const baseline = makeFixture("baseline");
  expectPass("inventory generation", run(baseline, "--write"));
  expectPass("matching inventory", run(baseline));

  const workspace = makeFixture("workspace", { workspace: true });
  expectPass("workspace inventory generation", run(workspace, "--write"));
  expectPass("matching workspace inventory", run(workspace));
  const workspaceInventory = JSON.parse(
    readFileSync(join(workspace, "docs", "reference", "dependency-inventory.json"), "utf8"),
  );
  assert.deepEqual(
    workspaceInventory.npmPackages.find((entry) => entry.name === "fixture-runtime").direct,
    [{ workspace: "apps/web", scope: "runtime" }],
  );

  const stale = makeFixture("stale");
  expectPass("stale fixture generation", run(stale, "--write"));
  const inventoryPath = join(stale, "docs", "reference", "dependency-inventory.json");
  writeFileSync(
    inventoryPath,
    readFileSync(inventoryPath, "utf8").replace('"version": "1.0.0"', '"version": "1.0.1"'),
    "utf8",
  );
  expectFailure("stale inventory", run(stale), "inventory does not match");

  const unapproved = makeFixture("unapproved");
  const manifestPath = join(
    unapproved,
    "node_modules",
    ".pnpm",
    "fixture-tool@1.0.0",
    "node_modules",
    "fixture-tool",
    "package.json",
  );
  writeFileSync(
    manifestPath,
    readFileSync(manifestPath, "utf8").replace('"MIT"', '"GPL-3.0-only"'),
    "utf8",
  );
  const unapprovedMetadataPath = join(unapproved, "config", "npm-package-metadata.json");
  writeFileSync(
    unapprovedMetadataPath,
    readFileSync(unapprovedMetadataPath, "utf8").replace(
      '"name": "fixture-tool",\n      "version": "1.0.0",\n      "license": "MIT"',
      '"name": "fixture-tool",\n      "version": "1.0.0",\n      "license": "GPL-3.0-only"',
    ),
    "utf8",
  );
  expectFailure("unapproved license", run(unapproved, "--write"), "npm license is not approved");

  const missingMetadata = makeFixture("missing-metadata");
  const missingMetadataPath = join(missingMetadata, "config", "npm-package-metadata.json");
  writeFileSync(
    missingMetadataPath,
    readFileSync(missingMetadataPath, "utf8").replace(
      /,\n    \{\n      "name": "platform-only"[\s\S]+?\n    \}/,
      "",
    ),
    "utf8",
  );
  expectFailure(
    "missing cross-platform metadata",
    run(missingMetadata, "--write"),
    "missing from the npm license metadata cache",
  );

  const staleMetadata = makeFixture("stale-metadata");
  const staleMetadataPath = join(staleMetadata, "config", "npm-package-metadata.json");
  writeFileSync(
    staleMetadataPath,
    readFileSync(staleMetadataPath, "utf8").replace(
      platformOnlyIntegrity,
      "sha512-c3RhbGUtbWV0YWRhdGE=",
    ),
    "utf8",
  );
  expectFailure(
    "stale metadata integrity",
    run(staleMetadata, "--write"),
    "integrity differs from pnpm-lock.yaml",
  );

  const extraneousInstall = makeFixture("extraneous-install");
  const extraneousManifest = join(
    extraneousInstall,
    "node_modules",
    ".pnpm",
    "stale-package@1.0.0",
    "node_modules",
    "stale-package",
    "package.json",
  );
  mkdirSync(resolve(extraneousManifest, ".."), { recursive: true });
  writeFileSync(
    extraneousManifest,
    `${JSON.stringify({ name: "stale-package", version: "1.0.0", license: "MIT" })}\n`,
    "utf8",
  );
  expectFailure(
    "extraneous installed package",
    run(extraneousInstall, "--write"),
    "installed npm package is absent from pnpm-lock.yaml",
  );

  const missingNotice = makeFixture("missing-notice");
  writeFileSync(join(missingNotice, "THIRD_PARTY_NOTICES.md"), "# Empty notices\n", "utf8");
  expectFailure("missing direct notice", run(missingNotice, "--write"), "direct dependency notice");

  const missingWorkspaceNotice = makeFixture("missing-workspace-notice", { workspace: true });
  writeFileSync(
    join(missingWorkspaceNotice, "THIRD_PARTY_NOTICES.md"),
    "| [fixture-tool](https://example.com/) | Test | MIT |\n",
    "utf8",
  );
  expectFailure(
    "missing workspace direct notice",
    run(missingWorkspaceNotice, "--write"),
    "fixture-runtime",
  );

  const unlistedArtifact = makeFixture("unlisted-artifact");
  writeFileSync(
    join(unlistedArtifact, "compose.yaml"),
    "services:\n  database:\n    image: example.invalid/database:1.0.0\n",
    "utf8",
  );
  expectFailure(
    "unlisted external artifact",
    run(unlistedArtifact, "--write"),
    "referenced external artifact is missing",
  );

  console.log("License checker tests passed (10 cases).");
} finally {
  rmSync(fixtureRoot, { force: true, recursive: true });
}
